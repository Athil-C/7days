/**
 * Precise showcase category filter.
 * Ensures clicking a category card only displays strictly relevant products
 * without false positives (e.g. no bath items or shopping carts under Battery Operated Jeep).
 */
export function isProductInShowcaseCategory(product, showcaseId) {
  if (!product) return false;
  if (!showcaseId || showcaseId === 'all') return true;

  const name = (product.name || '').toLowerCase();
  const badge = (product.badge || '').toLowerCase();
  const text = `${name} ${badge}`;

  switch (showcaseId) {
    case 'battery-jeep': {
      // Must have actual vehicle in title (jeep, car, suv, truck)
      const isVehicleName = /\b(jeep|jeeps|car|cars|suv|suvs|truck|trucks)\b/i.test(name);
      // Must be powered / battery / electric / remote control
      const isPowered = /\b(battery|electric|ride[- ]on|remote|rechargeable|rc|4x4|motorized)\b/i.test(text);
      // Strict negative exclusions: no nasal aspirators, bath kits, shopping carts, walkers, teethers, etc.
      const isExcluded = /\b(cart|aspirator|nasal|sucker|bath|chair|walker|crib|cradle|teether|mat|bed|sipper|bottle|clothes|swing car)\b/i.test(name);
      return isVehicleName && isPowered && !isExcluded;
    }

    case 'bike': {
      const hasBike = /\b(bike|bikes|motorbike|motorbikes|motorcycle|motorcycles)\b/i.test(name);
      const isExcluded = /\b(pump|walker|bath|crib|cradle|teether|mat|bottle|aspirator|gun|striker)\b/i.test(name);
      return hasBike && !isExcluded;
    }

    case 'study-table': {
      return /\b(study table|desk|desks|activity table|drawing table)\b/i.test(name) && !name.includes('high chair');
    }

    case 'high-chairs': {
      return /\b(high chair|high chairs|booster seat|dining chair)\b/i.test(name) && !name.includes('desk');
    }

    case 'tricycle': {
      // Must be an actual tricycle/trike, strictly excluding guns like 'Striker'
      const isTrike = /\b(trike|trikes|tricycle|tricycles)\b/i.test(name);
      const isExcluded = /\b(scooter|scooters|striker|gun|guns|pistol|rifle|nerf|jeep|aspirator)\b/i.test(name);
      return isTrike && !isExcluded;
    }

    case 'ride-ons': {
      const isRideOn = /\b(swing car|swing cars|twister car|twister cars|magic car|magic cars|push car|push cars|foot[- ]to[- ]floor)\b/i.test(name);
      const isElectric = /\b(battery|electric|rechargeable|motorized|remote)\b/i.test(name);
      return isRideOn && !isElectric;
    }

    case 'baby-walker': {
      return /\b(walker|walkers)\b/i.test(name) && !/\b(jeep|car|bike|gun|trike|aspirator)\b/i.test(name);
    }

    case 'stroller': {
      return /\b(stroller|strollers|pram|prams|buggy|pushchair)\b/i.test(name) && !name.includes('walker');
    }

    case 'scooter': {
      return /\b(scooter|scooters)\b/i.test(name) && !name.includes('walker');
    }

    case 'pretend-play': {
      return /\b(kitchen|doctor|cooking|pretend|playset|play set|tool set|doll|dollhouse)\b/i.test(name) && !/\b(stroller|jeep|bike|aspirator|walker)\b/i.test(name);
    }

    case 'educational': {
      return /\b(puzzle|puzzles|montessori|math|counting|wooden blocks?|building blocks?|magnetic tiles?|abacus)\b/i.test(name) && !/\b(stroller|bath|aspirator|walker|jeep)\b/i.test(name);
    }

    default:
      return true;
  }
}

